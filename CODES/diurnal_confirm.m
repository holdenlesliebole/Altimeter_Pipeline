fprintf('\n%-46s %-10s %7s %6s  %s\n','file','strongMon','range','peakHr','class');
fprintf('%s\n',repmat('-',1,90));
for i=1:numel(targets)
  [~,nm,ext]=fileparts(targets{i}); nm=[nm ext];
  if ~isfile(targets{i}); fprintf('%-46s (missing)\n',nm); continue; end
  try TT=read_rangelogger_log(targets{i}); catch; fprintf('%-46s (read fail)\n',nm); continue; end
  t=TT.Time; t.TimeZone=''; T=TT.Temperature_C; g=isfinite(T); t=t(g); T=T(g);
  ym=dateshift(t,'start','month'); um=unique(ym);
  bestRange=0; bestPk=NaN; bestMon='';
  for m=1:numel(um)
    sel=ym==um(m); hh=hour(t(sel)); T2=T(sel);
    mu=nan(24,1); for q=0:23; k=hh==q; if nnz(k)>10; mu(q+1)=mean(T2(k)); end; end
    if nnz(isfinite(mu))<20; continue; end
    mu=mu-mean(mu,'omitnan'); rng=max(mu)-min(mu);
    if rng>bestRange; bestRange=rng; [~,ix]=max(mu); bestPk=ix-1; bestMon=datestr(um(m),'yyyy-mm'); end
  end
  if isnan(bestPk); cls='(no diurnal signal)';
  elseif bestRange<0.4; cls=sprintf('weak(%.2fC) - inconclusive',bestRange);
  elseif bestPk>=13 && bestPk<=19; cls='LOCAL (unexpected!)';
  elseif bestPk>=21 || bestPk<=3; cls='UTC (confirms 0)';
  else; cls=sprintf('ambiguous (pk %02dh)',bestPk); end
  fprintf('%-46s %-10s %6.2fC %5s  %s\n', nm, bestMon, bestRange, sprintf('%02dh',bestPk), cls);
end
